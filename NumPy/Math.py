import numpy as np

arr = np.array([10, 20, 30, 40])

# Add 5 to every element of the array
print(arr + 5)

# Subtract 5 from every element of the array
print(arr - 5)

# Multiply every element by 2
print(arr * 2)

# Divide every element by 2
print(arr / 2)

# Calculate the square of every element
print(arr ** 2)


a = np.array([10, 20, 30])

b = np.array([40, 50, 60])

# Add corresponding elements of two arrays
print(a + b)

# Calculate the dot product of two arrays
print(np.dot(a, b))