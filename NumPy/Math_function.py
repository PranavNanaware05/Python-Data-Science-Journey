import numpy as np

arr = np.array([10, 20, 30, 40, 50])

# Calculate the mean (average) of the array
print(np.mean(arr))

# Calculate the median (middle value) of the array
print(np.median(arr))

# Find the minimum value in the array
print(np.min(arr))

# Find the maximum value in the array
print(np.max(arr))

# Calculate the standard deviation of the array
print(np.std(arr))

# Calculate the sum of all values in the array
print(np.sum(arr))

# Calculate the 1st percentile of the array
print(np.percentile(arr, 1))